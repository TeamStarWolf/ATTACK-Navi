// Tests for scripts/lint-truth-vocab.mjs, including the planted-violation case
// the E1.1 acceptance criteria ask for: a banned word planted in a template
// must make the CLI exit 1 and name the file and line.
// Run with: node --test scripts/lint-truth-vocab.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { RUNGS, RULES, lintText, lintRepo, targetFiles } from './lint-truth-vocab.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCRIPT = join(ROOT, 'scripts', 'lint-truth-vocab.mjs');

/** Rule ids found in `text`, in order. */
const rules = (text, kind) => lintText(text, kind).findings.map(f => f.rule);
const matches = (text, kind) => lintText(text, kind).findings.map(f => `${f.rule}:${f.match}`);

// ─── The allowlist is plan 4.1's ───────────────────────────────────────────

test('the rung allowlist is the "Allowed words" column of plan 4.1', () => {
  assert.deepEqual(RUNGS.known.allowed, ['mapped', 'available', 'reference depth']);
  assert.deepEqual(RUNGS.covered.allowed,
    ['covered (self-attested)', 'covered (range)', 'deployed', 'implemented (self-attested)', 'partial', 'planned']);
  assert.deepEqual(RUNGS.proven.allowed, ['proven', 'validated on <date> by <source>', 'defended']);
  assert.deepEqual(RUNGS.covered.qualifiers, ['self-attested', 'range']);
  assert.deepEqual(RULES.map(r => r.id),
    ['banned', 'letter-grade', 'covered-unqualified', 'proven-only', 'posture-claim', 'retired-label']);
});

// ─── Rules ─────────────────────────────────────────────────────────────────

test("plan 4.1's banned-everywhere words are flagged", () => {
  assert.deepEqual(rules('<span>LOW RISK</span>', 'html'), ['banned']);
  assert.deepEqual(rules('<span>Low-risk tactic</span>', 'html'), ['banned']);
  assert.deepEqual(rules('<p>Well Protected</p>', 'html'), ['banned']);
  assert.deepEqual(rules('<div>Coverage Score</div>', 'html'), ['banned']);
});

test('letter grades are flagged; words that only contain "grade" are not', () => {
  assert.deepEqual(rules('<div>Grade {{ g }}</div>', 'html'), ['letter-grade']);
  assert.deepEqual(rules('<b>Excellent posture.</b>', 'html'), ['letter-grade']);
  assert.deepEqual(rules('<p>a government-grade spyware; please upgrade; no grades</p>', 'html'), []);
});

test("'covered' needs its qualifier", () => {
  assert.deepEqual(rules('<th>Techniques Covered</th>', 'html'), ['covered-unqualified']);
  assert.deepEqual(rules('<p>covered (self-attested)</p><p>Covered (range)</p>', 'html'), []);
  assert.deepEqual(rules('<p>COVERED self-attested</p><p>Covered, self-attested</p>', 'html'), []);
  // 'uncovered' and 'discovered' are not 'covered'; 'uncovered' is a retired label.
  assert.deepEqual(rules('<p>discovered</p>', 'html'), []);
  assert.deepEqual(rules('<p>Top Uncovered</p>', 'html'), ['retired-label']);
});

test("'proven', 'validated' and 'defended' are Proven-only; a negation is not a claim", () => {
  assert.deepEqual(rules('<p>Validated</p>', 'html'), ['proven-only']);
  assert.deepEqual(rules('<p>Defended</p>', 'html'), ['proven-only']);
  assert.deepEqual(rules('<p>proven attack patterns</p>', 'html'), ['proven-only']);
  assert.deepEqual(rules('<p>self-attested, not validated; never proven; **not** a validated result</p>', 'html'), []);
});

test("posture claims with 'secure', 'compliant' or 'safe' are flagged; names are not", () => {
  assert.deepEqual(rules('<p>Your estate is secure.</p>', 'html'), ['posture-claim']);
  assert.deepEqual(rules('<p>Fully compliant</p>', 'html'), ['posture-claim']);
  assert.deepEqual(rules('<p>safe against T1059</p>', 'html'), ['posture-claim']);
  assert.deepEqual(rules('<p>CIS 4 Secure Configuration; Secure backend proxy; Require compliant devices</p>', 'html'), []);
  assert.deepEqual(rules('<p>Blank means NOT KNOWN TO US, not safe.</p>', 'html'), []);
});

test('labels retired by E1.1 PR 1 and PR 2 are flagged once each', () => {
  assert.deepEqual(matches('<p>Unified Coverage</p>', 'html'), ['retired-label:Unified Coverage']);
  assert.deepEqual(matches('<p>🎯 Unified</p>', 'html'), ['retired-label:Unified']);
  assert.deepEqual(rules('<p>Wazuh XDR</p><p>Risk Score</p><p>Intel Coverage %</p>', 'html'),
    ['retired-label', 'retired-label', 'retired-label']);
  assert.deepEqual(rules("const s = '# Generated by MITRE ATT&CK Navigator';", 'ts'), ['retired-label']);
  // The lower-case heat= value is not the label.
  assert.deepEqual(rules('| 4 | unified | 0 |', 'md'), []);
});

test('naming the vocabulary is not a claim', () => {
  assert.deepEqual(rules('<p>Lens labels follow the Known / Covered / Proven vocabulary.</p>', 'html'), []);
  assert.deepEqual(rules('The Known, Covered and Proven rungs.', 'md'), []);
});

// ─── What is scanned ───────────────────────────────────────────────────────

test('HTML: text, human-facing attributes and literals in bindings; not class names or keys', () => {
  assert.deepEqual(rules('<span class="covered" [class.covered]="x" id="covered">ok</span>', 'html'), []);
  assert.deepEqual(rules('<button title="Total techniques covered">x</button>', 'html'), ['covered-unqualified']);
  assert.deepEqual(rules('<i aria-label="Protected"></i>', 'html'), ['banned']);
  assert.deepEqual(rules(`<b [title]="n + ' covered (' + p + '%)'">x</b>`, 'html'), ['covered-unqualified']);
  assert.deepEqual(rules(`<b>{{ ok ? 'All covered' : 'Gap' }}</b>`, 'html'), ['covered-unqualified']);
  assert.deepEqual(rules(`@if (state === 'covered') { <b>{{ count }}</b> }`, 'html'), []);
  assert.deepEqual(rules('<!-- Coverage Score card --><div>ok</div>', 'html'), []);
});

test('TS: string literals and template text; not comments, imports, keys or identifier-like literals', () => {
  const src = [
    "import { covered } from './covered';",
    '// Coverage Score, LOW RISK, covered: comments are not scanned',
    "type S = 'covered' | 'gap';",
    "const a = { 'Techniques Covered': 1 };",
    "if (x === 'covered') {}",
    "const rung = { rung: 'Covered', qualifier: 'self-attested' };",
    "const label = 'Techniques Covered';",
    'const t = `${n} techniques covered`;',
  ].join('\n');
  const found = lintText(src, 'ts').findings;
  assert.deepEqual(found.map(f => [f.line, f.rule]), [[7, 'covered-unqualified'], [8, 'covered-unqualified']]);
});

test('TS: an inline component template is read as HTML', () => {
  const src = "@Component({ selector: 'x-covered', template: `<div class=\"covered\">Well Protected</div>` })\nclass X {}";
  assert.deepEqual(rules(src, 'ts'), ['banned']);
});

test('markdown: prose only, not code fences, inline code or link targets', () => {
  const md = [
    'Prose says covered here.',
    '```',
    'LOW RISK inside a fence',
    '```',
    'The `covered` key and [a link](docs/covered.md) are fine.',
    '<!-- Coverage Score in a comment -->',
  ].join('\n');
  assert.deepEqual(lintText(md, 'md').findings.map(f => [f.line, f.rule]), [[1, 'covered-unqualified']]);
});

test('positions are file:line:col, with CRLF line endings too', () => {
  const html = '<div>\r\n  <p>ok</p>\r\n  <p>LOW RISK</p>\r\n</div>\r\n';
  const [f] = lintText(html, 'html', 'src/app/x.html').findings;
  assert.deepEqual([f.file, f.line, f.col, f.rule, f.match], ['src/app/x.html', 3, 6, 'banned', 'LOW RISK']);
});

// ─── Allow directives ──────────────────────────────────────────────────────

test('an allow directive with a reason suppresses its rule on its line or the next', () => {
  const html = [
    '<p>Validated on 2026-10-13 by wazuh:100821</p> <!-- truth-vocab-allow proven-only -- Lylat range row, dated -->',
    '<!-- truth-vocab-allow-next-line banned,covered-unqualified -- quoted CWE title -->',
    '<p>Insufficiently Protected Credentials, covered</p>',
  ].join('\n');
  const result = lintText(html, 'html');
  assert.deepEqual(result.findings, []);
  assert.equal(result.directives.length, 2);
  const ts = "const t = 'Validated'; // truth-vocab-allow proven-only -- validation run result, Proven data";
  assert.deepEqual(rules(ts, 'ts'), []);
});

test('a directive only allows the rules it names', () => {
  const html = '<!-- truth-vocab-allow-next-line banned -- reason -->\n<p>Protected, covered</p>';
  assert.deepEqual(rules(html, 'html'), ['covered-unqualified']);
});

test('a directive without a reason, with an unknown rule, or that allows nothing is itself a finding', () => {
  assert.deepEqual(rules('<p>LOW RISK</p> <!-- truth-vocab-allow banned -->', 'html'), ['bad-allow', 'banned']);
  assert.deepEqual(rules('<p>LOW RISK</p> <!-- truth-vocab-allow no-such-rule -- why -->', 'html'), ['bad-allow', 'banned']);
  assert.deepEqual(rules('<!-- truth-vocab-allow-next-line banned -- stale -->\n<p>fine</p>', 'html'), ['unused-allow']);
});

// ─── CLI: a planted violation fails ────────────────────────────────────────

function plantRepo(files) {
  const dir = mkdtempSync(join(tmpdir(), 'truth-vocab-'));
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  }
  return dir;
}

test('planted violation: the CLI exits 1 and reports file:line', () => {
  const dir = plantRepo({
    'src/app/dash/dash.component.html': '<div>\n  <span>{{ score }}</span>\n  <span class="risk">LOW RISK</span>\n</div>\n',
    'src/app/dash/dash.component.ts': "export const LABEL = 'Mitigations mapped';\n",
    'src/app/dash/dash.component.spec.ts': "expect(text).not.toContain('LOW RISK');\n",
    'README.md': '# Sample\n\nReference depth is Known data.\n',
  });
  try {
    const run = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
    assert.equal(run.status, 1, run.stdout + run.stderr);
    assert.match(run.stdout, /^src\/app\/dash\/dash\.component\.html:3:22 {2}banned {2}"LOW RISK"/m);
    assert.match(run.stdout, /lint-truth-vocab: 1 finding in 3 files/);
    // Spec files are not scanned: they assert the banned words are gone.
    assert.doesNotMatch(run.stdout, /\.spec\.ts/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('the CLI exits 0 on a clean tree and --json reports the findings', () => {
  const dir = plantRepo({
    'src/app/a/a.component.html': '<p>Mitigations mapped: {{ n }}</p>\n',
    'docs/GUIDE.md': 'Covered (self-attested) means you declared it.\n',
  });
  try {
    const clean = spawnSync(process.execPath, [SCRIPT, '--root', dir], { encoding: 'utf8' });
    assert.equal(clean.status, 0, clean.stdout + clean.stderr);
    assert.match(clean.stdout, /0 findings in 2 files/);
    writeFileSync(join(dir, 'docs/GUIDE.md'), 'You are fully compliant.\n');
    const dirty = spawnSync(process.execPath, [SCRIPT, '--root', dir, '--json'], { encoding: 'utf8' });
    assert.equal(dirty.status, 1);
    const report = JSON.parse(dirty.stdout);
    assert.deepEqual(report.findings.map(f => [f.file, f.line, f.rule]), [['docs/GUIDE.md', 1, 'posture-claim']]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

// ─── This repository ───────────────────────────────────────────────────────

test('targets: src/app templates and non-spec TS, README and docs markdown', () => {
  const files = targetFiles(ROOT);
  assert.ok(files.includes('README.md'));
  assert.ok(files.includes('docs/HEATMAPS.md'));
  assert.ok(files.some(f => f.startsWith('src/app/') && f.endsWith('.component.html')));
  assert.ok(files.some(f => f.startsWith('src/app/') && f.endsWith('.service.ts')));
  assert.ok(!files.some(f => f.endsWith('.spec.ts') || f.startsWith('src/app/testing/')));
});

test('this repository lints clean (E1.1: lint reports 0 violations)', () => {
  const { findings } = lintRepo(ROOT);
  assert.deepEqual(findings.map(f => `${f.file}:${f.line}:${f.col} ${f.rule} "${f.match}"`), []);
});
