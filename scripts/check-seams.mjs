// Seam check (Phase 2 design §3 P2-08, §4.2; R10). Three rules:
//
//   posture-rollup: a non-spec file under src/app that names BOTH a
//   mitigation-to-technique map or lookup (the first regex) AND the mitigation
//   implementation store (the second) can fold "mitigation implemented" into a
//   technique answer outside PostureService. Every such file must be on the
//   allow-list with its remaining uses, a reason, and the PR or epic that
//   removes it (or why it stays).
//
//   one-picker (P2-12b, E2.6): a file outside threat-profile-picker that reads
//   domain.groups AND filters by alias (aliases.some(...)) is a rival group
//   picker; it must be on the allow-list with a reason (§10.4 item 8). The
//   rationale comment on the rule below records why alias, not name (P2-17).
//
//   picker-select (RP-F item 3): a non-spec file outside threat-profile-picker
//   that calls selectGroup( or selectCampaign(, the picker's selection
//   methods, is choosing a group beside the picker (the emulation panel's
//   Common picks did, so its "Selected:" line and the picker disagreed). It
//   must be on the allow-list with a reason. It does not widen one-picker.
//
// The allow-list (scripts/check-seams.allowlist.json) is GENERATED by this
// script from the grep, never written by hand: `--write` sets its membership
// and each entry's uses from the tree, keeps the bucket, reason and removedBy
// of files that still match, drops files that no longer match, and adds new
// matches with empty annotations, which the check then rejects until a person
// fills them in (so a new seam use is a reviewed diff, never silent).
//
// Every rule (posture-rollup, one-picker and picker-select) is checked every
// run, each with its own allow-list entries. The check fails on, for any rule:
//   - a matching file that is not listed (a new seam use for that rule);
//   - a listed file that no longer matches (a stale entry: regenerate — the
//     posture-rollup list shrinks as files move to PostureService, the
//     one-picker list as rival pickers move to threat-profile-picker);
//   - a listed entry without a reason or removedBy.
// A listed file whose uses changed passes with a note to regenerate.
//
//   node scripts/check-seams.mjs                    check this repository, print the list
//   node scripts/check-seams.mjs --write            regenerate the allow-list from the tree
//   node scripts/check-seams.mjs --root DIR         check DIR instead (tests)
//   node scripts/check-seams.mjs --allowlist FILE   read or write FILE instead

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CODE_DIR = 'src/app';
export const DEFAULT_ALLOWLIST = 'scripts/check-seams.allowlist.json';

/**
 * The rules. Each fails a file that matches every one of its regexes; a rule's
 * optional `exclude` regex (tested against the repository-relative path) skips a
 * file before it is read — used to let the one allowed implementation through.
 */
export const RULES = {
  'posture-rollup': {
    summary: 'mitigation-to-technique map AND the mitigation implementation store in one file',
    patterns: [
      /mitigationsByTechnique|techniquesByMitigation|getTechniquesForMitigation|getMitigationsForTechnique/g,
      /ImplementationService|implService|getStatusMap|ImplStatus/g,
    ],
  },
  // E2.6 one-picker (P2-12b): only threat-profile-picker should offer a group
  // picker that filters the full group list by name or alias; every other
  // component selects groups through it (which emits STIX ids). A file that
  // reads `domain.groups` AND filters by alias (`aliases.some(...)`) is a rival
  // group/actor picker and must be on the allow-list with a reason (owner
  // decision, §10.4 item 8). The alias filter is the discriminator: only groups,
  // actors, software and campaigns carry aliases, so a technique-name filter
  // (`t.name.toLowerCase().includes`) never trips the rule, while a real group
  // picker always offers name-and-alias search. The picker itself is excluded.
  // Why alias and not name: this is a seam guard, not a security control; a
  // name-based clause cannot tell a group-name filter from a technique-name
  // filter without false positives, and false positives erode the allow-list
  // until it means nothing. The alias clause has zero false positives and
  // catches the form every removed rival actually took (name+alias search copied
  // from the real picker). Two rival forms it CANNOT catch are accepted as
  // review-caught, not lint-caught: (1) a name-only group filter over
  // `domain.groups` and (2) a bare `<select>`/list of `domain.groups` with no
  // filter at all. (Decisions sheet: P2-17.)
  'one-picker': {
    summary: 'a component outside threat-profile-picker reads domain.groups AND filters by alias (aliases.some())',
    exclude: /components\/threat-profile-picker\//,
    patterns: [
      /domain\.groups\b/g,
      /\baliases\.some\(/g,
    ],
  },
  // RP-F item 3: the picker's selection methods are called only inside the
  // picker. A caller binds the picker's (groupSelected) output, or passes its
  // presets as [quickPicks] (single mode), so the picker's list and the
  // caller's selection have one source. A direct call elsewhere is a second
  // selection path: the RP-F breaker found the emulation panel's six Common
  // picks calling the panel's own selectGroup() while the picker showed
  // nothing. The pattern is the call token, so a component's own method of
  // the same name also matches; such a file is listed with a reason. It is a
  // seam guard like one-picker, and it leaves one-picker's alias rule as
  // decided (P2-17).
  'picker-select': {
    summary: "a file outside threat-profile-picker calls selectGroup( or selectCampaign( (the picker's selection methods)",
    exclude: /components\/threat-profile-picker\//,
    patterns: [
      /\bselect(?:Group|Campaign)\(/g,
    ],
  },
};

// The remedy printed when a file matches a rule but is not on its allow-list.
// Per rule, because the fix differs: posture-rollup is about reading posture
// through the one service; one-picker is about selecting groups through the one
// picker. Either way, a legitimate exception is recorded with --write + a reason.
const REMEDIES = {
  'posture-rollup': 'read posture through PostureService',
  'one-picker': 'select groups through threat-profile-picker',
  'picker-select': "bind threat-profile-picker's (groupSelected) output or pass presets as [quickPicks]",
};

const posix = (p) => p.split(sep).join('/');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

/** Every non-spec file under src/app, repository-relative, sorted. */
export function codeFiles(root) {
  const dir = join(root, CODE_DIR);
  if (!existsSync(dir)) return [];
  return walk(dir)
    .map((f) => posix(relative(root, f)))
    .filter((f) => !f.endsWith('.spec.ts'))
    .sort();
}

/** Token -> count of every regex match in `text`, tokens sorted. */
function usesOf(text, patterns) {
  const counts = new Map();
  for (const re of patterns) {
    for (const m of text.matchAll(new RegExp(re.source, 'g'))) counts.set(m[0], (counts.get(m[0]) ?? 0) + 1);
  }
  return Object.fromEntries([...counts].sort(([a], [b]) => a.localeCompare(b)));
}

/** The files that match every regex of `rule`, each with its uses. */
export function scanRule(root, rule) {
  const { patterns, exclude } = RULES[rule];
  const hits = [];
  for (const file of codeFiles(root)) {
    if (exclude && exclude.test(file)) continue;
    const text = readFileSync(join(root, file), 'utf8');
    if (patterns.every((re) => new RegExp(re.source).test(text))) hits.push({ file, uses: usesOf(text, patterns) });
  }
  return hits;
}

export function readAllowlist(path) {
  if (!existsSync(path)) return { rules: {} };
  return JSON.parse(readFileSync(path, 'utf8'));
}

const sameUses = (a, b) => JSON.stringify(a ?? {}) === JSON.stringify(b ?? {});

/**
 * Problems and notes for every rule against the allow-list object.
 * Returns { problems: string[], notes: string[], listed: {rule: entries[]} }.
 */
export function checkSeams(root, allowlist) {
  const problems = [];
  const notes = [];
  const listed = {};
  for (const rule of Object.keys(RULES)) {
    const entries = allowlist.rules?.[rule]?.entries ?? [];
    listed[rule] = entries;
    const hits = new Map(scanRule(root, rule).map((h) => [h.file, h]));
    const byFile = new Map(entries.map((e) => [e.file, e]));
    for (const [file] of hits) {
      if (!byFile.has(file)) {
        problems.push(`${rule}: ${file} matches both regexes and is not on the allow-list: ${REMEDIES[rule] ?? 'remove the seam use'}, or run --write and give it a reason and removedBy`);
      }
    }
    for (const e of entries) {
      const hit = hits.get(e.file);
      if (!hit) {
        problems.push(`${rule}: ${e.file} is on the allow-list but no longer matches both regexes (stale entry): run node scripts/check-seams.mjs --write so the list shrinks`);
        continue;
      }
      if (!e.reason || !String(e.reason).trim() || !e.removedBy || !String(e.removedBy).trim()) {
        problems.push(`${rule}: ${e.file} is listed without a reason or removedBy`);
      }
      if (!sameUses(e.uses, hit.uses)) {
        notes.push(`${rule}: ${e.file} uses changed (listed ${JSON.stringify(e.uses ?? {})}, now ${JSON.stringify(hit.uses)}): run --write to record them`);
      }
    }
  }
  return { problems, notes, listed };
}

/** The allow-list regenerated from the tree, keeping the annotations of files that still match. */
export function generateAllowlist(root, previous) {
  const out = { generatedBy: 'node scripts/check-seams.mjs --write', rules: {} };
  for (const [rule, def] of Object.entries(RULES)) {
    const old = new Map((previous.rules?.[rule]?.entries ?? []).map((e) => [e.file, e]));
    out.rules[rule] = {
      summary: def.summary,
      patterns: def.patterns.map((re) => re.source),
      entries: scanRule(root, rule).map(({ file, uses }) => {
        const o = old.get(file) ?? {};
        return { file, uses, bucket: o.bucket ?? '', reason: o.reason ?? '', removedBy: o.removedBy ?? '' };
      }),
    };
  }
  return out;
}

function parseArgs(argv) {
  const args = { root: ROOT, allowlist: null, write: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--root') args.root = resolve(argv[++i]);
    else if (argv[i] === '--allowlist') args.allowlist = resolve(argv[++i]);
    else if (argv[i] === '--write') args.write = true;
    else throw new Error(`unknown argument: ${argv[i]}`);
  }
  args.allowlist ??= join(args.root, DEFAULT_ALLOWLIST);
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const previous = readAllowlist(args.allowlist);
  if (args.write) {
    const next = generateAllowlist(args.root, previous);
    writeFileSync(args.allowlist, JSON.stringify(next, null, 2) + '\n');
    for (const [rule, r] of Object.entries(next.rules)) console.log(`check-seams: wrote ${r.entries.length} ${rule} entries to ${posix(relative(args.root, args.allowlist))}`);
  }
  const allowlist = args.write ? readAllowlist(args.allowlist) : previous;
  const { problems, notes, listed } = checkSeams(args.root, allowlist);
  for (const [rule, entries] of Object.entries(listed)) {
    console.log(`check-seams: ${rule}: ${entries.length} allow-listed files`);
    for (const e of entries) {
      const uses = Object.entries(e.uses ?? {}).map(([k, v]) => `${k} x${v}`).join(', ');
      console.log(`  ${e.file}  [${e.bucket || '?'}; removed by ${e.removedBy || '?'}]  ${uses}`);
      console.log(`      ${e.reason || '(no reason)'}`);
    }
  }
  for (const n of notes) console.log(`note: ${n}`);
  if (problems.length) {
    for (const p of problems) console.error(`check-seams: ${p}`);
    console.error(`check-seams: ${problems.length} problem(s)`);
    process.exit(1);
  }
  console.log('check-seams: OK');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
