import { TestBed } from '@angular/core/testing';
import { provideHttpClient, withXhr } from '@angular/common/http';
import { provideHttpClientTesting } from '@angular/common/http/testing';
import { SigmaService, SIGMA_GENERATOR_AUTHOR } from './sigma.service';
import { Technique } from '../models/technique';

describe('SigmaService', () => {
  let service: SigmaService;

  beforeEach(() => {
    TestBed.configureTestingModule({
      providers: [provideHttpClient(withXhr()), provideHttpClientTesting()],
    });
    service = TestBed.inject(SigmaService);
  });

  describe('getRuleCount', () => {
    it('returns 0 for unknown technique', () => {
      expect(service.getRuleCount('T9999')).toBe(0);
    });

    it('returns a non-negative number for any input', () => {
      expect(service.getRuleCount('T1059')).toBeGreaterThanOrEqual(0);
    });
  });

  describe('getHeatScore', () => {
    it('returns a non-negative number', () => {
      expect(service.getHeatScore('T1059')).toBeGreaterThanOrEqual(0);
    });
  });

  describe('getLiveCounts', () => {
    it('returns a Map', () => {
      expect(service.getLiveCounts() instanceof Map).toBe(true);
    });
  });

  describe('getCachedRules', () => {
    it('returns undefined for unknown technique before any fetch', () => {
      expect(service.getCachedRules('T9999')).toBeUndefined();
    });
  });

  describe('generated template author (E1.1)', () => {
    // A technique the generator has a template for (E1.6 dropped the generic
    // fallback, so T1059 itself no longer gets one).
    const tech = {
      id: 'attack-pattern--1',
      attackId: 'T1059.001',
      name: 'PowerShell',
      tacticShortnames: ['execution'],
      platforms: ['Windows'],
      dataSources: [],
      detectionText: '',
      isSubtechnique: false,
    } as unknown as Technique;

    it('names this project as the generator', () => {
      const yaml = service.generateRuleForTechnique(tech)!.yaml;
      expect(SIGMA_GENERATOR_AUTHOR).toBe('Generated by ATTACK-Navi');
      expect(yaml).toContain(`author: '${SIGMA_GENERATOR_AUTHOR}'`);
    });

    it('never borrows the ATT&CK Navigator name, in single or bulk output', () => {
      const single = service.generateRuleForTechnique(tech)!.yaml;
      const bulk = service.generateRulesForTechniques([tech, { ...tech, attackId: 'T1059.003', name: 'Windows Command Shell' } as Technique]);
      for (const text of [single, bulk]) {
        expect(text).not.toMatch(/Navigator/i);
        for (const line of text.split('\n').filter(l => l.startsWith('author:'))) {
          expect(line).toBe(`author: '${SIGMA_GENERATOR_AUTHOR}'`);
        }
      }
    });
  });
});
